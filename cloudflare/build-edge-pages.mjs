// Builds the HTML the Worker serves while the container is asleep (see edge.mjs).
// wrangler.jsonc runs this before every `wrangler deploy` and `wrangler dev` ("build"), so the
// pages always come from the same checkout as the container image and the static assets.
//
// Same output as datemate/app/static_pages.py versioned_page(): every /static/*.js|css
// address gets ?v=<first 12 hex of the file's SHA-256>, so a deploy changes the addresses.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const DATEMATE_ROOT = path.join(HERE, "..", "datemate");
export const OUTPUT = path.join(HERE, "generated", "edge-pages.mjs");
// Request path -> file in datemate/static, as the app routes them (main.py, sharing.py).
export const EDGE_PAGE_FILES = Object.freeze({ "/": "index.html", "/shared": "shared.html" });

export function versionedPage(name, root = DATEMATE_ROOT) {
  // Python's read_text() turns \r\n and \r into \n; the hashes use the raw bytes.
  const html = readFileSync(path.join(root, "static", name), "utf8").replace(/\r\n?/g, "\n");
  return html.replace(/(\/static\/[^\s"'<>?]+\.(?:js|css))/g, (url) => {
    const file = path.join(root, ...url.split("/").filter(Boolean));
    if (!existsSync(file) || !statSync(file).isFile()) return url;
    return url + "?v=" + createHash("sha256").update(readFileSync(file)).digest("hex").slice(0, 12);
  });
}

export function buildEdgePages(root = DATEMATE_ROOT) {
  return Object.fromEntries(Object.entries(EDGE_PAGE_FILES).map(([route, name]) => [route, versionedPage(name, root)]));
}

export function writeEdgePages(output = OUTPUT, root = DATEMATE_ROOT) {
  const pages = buildEdgePages(root);
  mkdirSync(path.dirname(output), { recursive: true });
  writeFileSync(output, "// Generated by cloudflare/build-edge-pages.mjs. Do not edit; not committed.\n"
    + `export const EDGE_PAGES = ${JSON.stringify(pages, null, 2)};\n`);
  return pages;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const pages = writeEdgePages();
  console.log(`edge pages: ${Object.keys(pages).join(", ")} -> ${path.relative(process.cwd(), OUTPUT)}`);
}
