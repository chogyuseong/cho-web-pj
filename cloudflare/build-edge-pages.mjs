// Builds the HTML the Worker serves while the container is asleep (see edge.mjs).
// wrangler.jsonc runs this before every `wrangler deploy` and `wrangler dev` ("build"), so the
// pages always come from the same checkout as the container image and the static assets.
//
// Same output as datemate/app/static_pages.py versioned_page(): every /static/*.js|css
// address gets ?v=<first 12 hex of the file's SHA-256>, so a deploy changes the addresses.
// It also writes the JS bundles (static/bundles/*.js, see "JS 묶기" below) before building the pages.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const DATEMATE_ROOT = path.join(HERE, "..", "datemate");
export const OUTPUT = path.join(HERE, "generated", "edge-pages.mjs");
// Request path -> file in datemate/static, as the app routes them (main.py, sharing.py).
// "404" is not a route: it is the HTML not-found page (static_pages.NOT_FOUND_PAGE) that edge.mjs notFound() sends
// to browser page requests, as the app's http_error handler does.
export const EDGE_PAGE_FILES = Object.freeze({ "/": "index.html", "/shared": "shared.html", "404": "not-found.html" });

// ── JS 묶기(QA-14, 2026-11-27) ──────────────────────────────────────────────────────────────
// 왜: 첫 화면이 defer 스크립트 46개를 따로 받는데, 브라우저는 낮은 우선순위 요청을 몇 개씩만 동시에 보내
//     파일마다 1ms 면 끝나는 응답이 왕복 대기(운영 측정 약 0.35~0.4초)를 열 번 가까이 쌓았다
//     (운영 측정: DOMContentLoaded 약 4.4초, 느린 4G·CPU 4배 9.5초). 하나로 묶으면 그 대기가 한 번이 된다.
// 무엇을: 페이지 안에서 공백만 사이에 두고 이어진 <script src="/static/X.js" defer></script> 2개 이상 덩어리를
//     static/bundles/<페이지 이름>.js 하나로 이어 붙이고, 페이지에는 그 태그 하나만 남긴다.
//     원본 HTML(index.html·shared.html)과 원본 JS 는 그대로다 — 사람이 고치는 곳은 계속 원본이다.
// 오래된 묶음 막기: 묶음 맨 위에 원본 파일별 내용 해시를 적는다(bundleHeader). 페이지를 만들 때 그 머리가
//     지금 원본과 글자까지 같을 때만 묶음 태그로 바꾸고, 다르거나 없으면 예전처럼 파일 46개를 그대로 둔다.
//     앱(datemate/app/static_pages.py bundled_page)도 같은 규칙이라, 두 쪽 페이지가 같다(tests 가 비교).
// 함께 바꿀 것: SCRIPT_RUN·SCRIPT_SRC 정규식, 머리 글(BUNDLE_HEADER_FIRST_LINE), 파일 사이 구분(bundleSource)은
//     static_pages.py 의 _SCRIPT_RUN·_SCRIPT_SRC·BUNDLE_HEADER_FIRST_LINE 과 똑같아야 한다.
// 묶음 안의 동작 차이(일부러 둔 것):
//   · 파일 맨 위 'use strict' 는 묶음의 첫 파일이 아니면 무시된다(그 파일들은 엄격하지 않은 모드로 돈다 —
//     엄격 모드는 오류를 더 내는 쪽이라 정상 동작은 같다).
//   · 한 파일의 맨 위 코드가 실행 중 오류를 내면 그 뒤 파일도 멈춘다(예전엔 그 파일만). 테스트 전체로 확인한다.
//   · 파일 사이에 줄바꿈과 ';' 를 넣어 앞 파일 끝과 뒤 파일 첫 줄이 한 문장으로 붙지 않게 하고(세미콜론 자동
//     삽입 함정), 파일 맨 앞 BOM(U+FEFF)은 뺀다.
// 덩어리가 둘인 페이지(QA-19, 2026-11-28): 첫 화면(index.html)은 바로 받는 덩어리(→ bundles/index.js)와, <template id="later-scripts">
//     안에 적어 둔 덩어리(→ bundles/index-2.js, 둘째부터는 이름에 -2, -3 …)가 있다. template 안의 script 는 브라우저가 받지 않고,
//     첫 묶음의 static/later-scripts.js 가 DOMContentLoaded 뒤에 그 주소(묶음이면 하나, 원본 태그면 여러 개)를 순서대로 붙인다.
//     여기 로직은 덩어리가 어디 있는지 모른다 — 덩어리마다 따로 묶고, 따로 오래됐는지 보고, 아래 versionedPage 가 template 안 주소에도 ?v= 를 붙인다.
//     각 묶음의 첫 파일(ko-text.js, parking.js)에는 'use strict' 를 두지 않는다. 설계·되돌리는 법: datemate/docs/QA-19-js-split-design.ko.md
// 묶지 않으려면: static/bundles/ 를 지우면 된다(페이지가 원본 태그로 돌아간다). 기능을 아예 끄려면
//     writeEdgePages 의 writeBundles 호출과 static_pages.versioned_page 의 bundled_page 호출을 뺀다.
export const BUNDLE_DIR = "bundles";
export const BUNDLE_HEADER_FIRST_LINE = "/* datemate bundle: generated by cloudflare/build-edge-pages.mjs; do not edit, not committed.";
const SCRIPT_RUN = /<script src="\/static\/[^"?]+\.js" defer><\/script>(?:\s*<script src="\/static\/[^"?]+\.js" defer><\/script>)+/g;
const SCRIPT_SRC = /<script src="\/static\/([^"?]+\.js)" defer><\/script>/g;

function sourceHash(root, name) {
  const file = path.join(root, "static", ...name.split("/"));
  if (!existsSync(file) || !statSync(file).isFile()) return null;
  return createHash("sha256").update(readFileSync(file)).digest("hex").slice(0, 12);
}

// 묶음 맨 위 두 줄. 원본 하나라도 없으면 null(그 덩어리는 묶지 않는다).
export function bundleHeader(names, root = DATEMATE_ROOT) {
  const parts = [];
  for (const name of names) {
    const hash = sourceHash(root, name);
    if (!hash) return null;
    parts.push(`${name}=${hash}`);
  }
  return `${BUNDLE_HEADER_FIRST_LINE}\n   sources: ${parts.join(" ")} */\n`;
}

// 페이지 하나의 묶음 덩어리들: [{ file: "bundles/index.js", names: ["a.js", ...], tag: 원래 태그들 }]
export function pageBundles(name, html) {
  const stem = path.basename(name, path.extname(name));
  return [...html.matchAll(SCRIPT_RUN)].map((match, index) => ({
    file: `${BUNDLE_DIR}/${stem}${index ? `-${index + 1}` : ""}.js`,
    names: [...match[0].matchAll(SCRIPT_SRC)].map((m) => m[1]),
    tag: match[0],
  }));
}

function bundleSource(names, root) {
  const header = bundleHeader(names, root);
  if (!header) return null;
  return header + names.map((name) => {
    const text = readFileSync(path.join(root, "static", ...name.split("/")), "utf8").replace(/^﻿/, "");
    return `/* ---- ${name} ---- */\n${text}\n;\n`;
  }).join("");
}

// 배포 때 묶음 파일을 쓴다(writeEdgePages 가 페이지보다 먼저 부른다). 쓴 파일 경로 목록을 돌려준다.
export function writeBundles(root = DATEMATE_ROOT) {
  const written = [];
  for (const name of Object.values(EDGE_PAGE_FILES)) {
    const page = path.join(root, "static", name);
    if (!existsSync(page)) continue; // 시험용 폴더처럼 일부 페이지만 있는 경우
    const html = readFileSync(page, "utf8").replace(/\r\n?/g, "\n");
    for (const bundle of pageBundles(name, html)) {
      const source = bundleSource(bundle.names, root);
      if (!source) continue;
      const file = path.join(root, "static", ...bundle.file.split("/"));
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, source);
      written.push(bundle.file);
    }
  }
  return written;
}

// 디스크의 묶음 머리가 지금 원본과 같을 때만 그 덩어리를 묶음 태그 하나로 바꾼다.
export function bundledPage(name, html, root = DATEMATE_ROOT) {
  for (const bundle of pageBundles(name, html)) {
    const header = bundleHeader(bundle.names, root);
    const file = path.join(root, "static", ...bundle.file.split("/"));
    if (!header || !existsSync(file)) continue;
    if (!readFileSync(file).subarray(0, Buffer.byteLength(header)).equals(Buffer.from(header))) continue;
    html = html.replace(bundle.tag, `<script src="/static/${bundle.file}" defer></script>`);
  }
  return html;
}

export function versionedPage(name, root = DATEMATE_ROOT) {
  // Python's read_text() turns \r\n and \r into \n; the hashes use the raw bytes.
  const html = bundledPage(name, readFileSync(path.join(root, "static", name), "utf8").replace(/\r\n?/g, "\n"), root);
  return html.replace(/(\/static\/[^\s"'<>?]+\.(?:js|css))/g, (url) => {
    const file = path.join(root, ...url.split("/").filter(Boolean));
    if (!existsSync(file) || !statSync(file).isFile()) return url;
    return url + "?v=" + createHash("sha256").update(readFileSync(file)).digest("hex").slice(0, 12);
  });
}

export function buildEdgePages(root = DATEMATE_ROOT) {
  return Object.fromEntries(Object.entries(EDGE_PAGE_FILES).map(([route, name]) => [route, versionedPage(name, root)]));
}

export function writeEdgePages(output = OUTPUT, root = DATEMATE_ROOT) {
  // 묶음을 먼저 써야 페이지가 묶음 태그(와 그 ?v= 해시)를 쓴다. 묶음은 static/ 아래라 Workers 정적 파일과
  // 컨테이너 이미지(.dockerignore 의 datemate/static/**)에 함께 들어간다 — wrangler 는 이 build 를 docker build 보다 먼저 돌린다.
  writeBundles(root);
  const pages = buildEdgePages(root);
  mkdirSync(path.dirname(output), { recursive: true });
  writeFileSync(output, "// Generated by cloudflare/build-edge-pages.mjs. Do not edit; not committed.\n"
    + `export const EDGE_PAGES = ${JSON.stringify(pages, null, 2)};\n`);
  return pages;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const pages = writeEdgePages();
  console.log(`edge pages: ${Object.keys(pages).join(", ")} -> ${path.relative(process.cwd(), OUTPUT)}`);
}
