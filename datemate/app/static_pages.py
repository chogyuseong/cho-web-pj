import hashlib
import re
from html import escape
from .config import ROOT

_versions = {}


def file_version(url_path):
    """/static/... 파일의 현재 내용 해시(versioned_page 가 ?v= 로 붙이는 값). 파일이 없으면 None.

    변경 시각·크기가 같으면 다시 읽지 않는다. 주소가 static 폴더 밖을 가리키면 None.
    """
    static = (ROOT / "static").resolve()
    try:
        path = (ROOT / url_path.lstrip("/")).resolve()
        path.relative_to(static)
        stat = path.stat()
    except (OSError, ValueError):
        return None
    if not path.is_file():
        return None
    key = (str(path), stat.st_mtime_ns, stat.st_size)
    version = _versions.get(key)
    if version is None:
        version = hashlib.sha256(path.read_bytes()).hexdigest()[:12]
        _versions[key] = version
    return version


# JS 묶기(QA-14, 2026-11-27). 묶음 파일(static/bundles/<페이지>.js)은 배포 때 cloudflare/build-edge-pages.mjs 가 만든다
# (테스트는 tests/conftest.py 가 시작할 때 만든다). 여기서는 만들지 않고, 디스크의 묶음 머리가 지금 원본 해시와
# 글자까지 같을 때만 페이지의 이어진 defer 스크립트 태그들을 묶음 태그 하나로 바꾼다 — 다르거나 없으면 원본 태그 그대로
# (개발 중 JS 를 고치면 묶음이 오래돼 자동으로 원본 46개를 쓴다). 이유·묶음 안의 동작 차이·끄는 법은 build-edge-pages.mjs
# 의 'JS 묶기' 주석. 함께 바꿀 것: 아래 정규식 두 개와 BUNDLE_HEADER_FIRST_LINE·bundle_header 형식은 그 파일과 똑같아야 한다
# (tests/test_js_bundle.py 가 두 쪽 결과를 비교).
BUNDLE_DIR = "bundles"
BUNDLE_HEADER_FIRST_LINE = "/* datemate bundle: generated by cloudflare/build-edge-pages.mjs; do not edit, not committed."
_SCRIPT_RUN = re.compile(r'<script src="/static/[^"?]+\.js" defer></script>(?:\s*<script src="/static/[^"?]+\.js" defer></script>)+')
_SCRIPT_SRC = re.compile(r'<script src="/static/([^"?]+\.js)" defer></script>')


def bundle_header(names):
    """묶음 맨 위 두 줄(원본 파일별 내용 해시). 원본이 하나라도 없으면 None."""
    parts = []
    for name in names:
        version = file_version("/static/" + name)
        if version is None:
            return None
        parts.append(f"{name}={version}")
    return f"{BUNDLE_HEADER_FIRST_LINE}\n   sources: {' '.join(parts)} */\n"


def bundled_page(name, html):
    stem = name.rsplit(".", 1)[0]
    runs = list(_SCRIPT_RUN.finditer(html))
    for index, match in enumerate(runs):
        bundle = f"{BUNDLE_DIR}/{stem}{f'-{index + 1}' if index else ''}.js"
        header = bundle_header(_SCRIPT_SRC.findall(match.group(0)))
        path = ROOT / "static" / bundle
        if header is None or not path.is_file():
            continue
        expected = header.encode("utf-8")
        with path.open("rb") as file:
            if file.read(len(expected)) != expected:
                continue
        html = html.replace(match.group(0), f'<script src="/static/{bundle}" defer></script>', 1)
    return html


def versioned_page(name):
    """정적 HTML의 js·css 주소에 파일 내용 해시를 붙인다(묶음이 지금 원본과 맞으면 먼저 묶음 태그로 바꾼다).

    파일이 바뀌면 주소도 바뀌어, 배포 직후 브라우저가 이전 스크립트와 새 스크립트를 섞어 쓰지 않는다.
    """
    html = bundled_page(name, (ROOT / "static" / name).read_text(encoding="utf-8"))

    def versioned(match):
        url = match.group(1)
        path = ROOT / url.lstrip("/")
        if not path.is_file():
            return match.group(0)
        version = hashlib.sha256(path.read_bytes()).hexdigest()[:12]
        return url + "?v=" + version

    return re.sub(r'(/static/[^\s"\'<>?]+\.(?:js|css))', versioned, html)


# 첫 화면 head 의 canonical·og:url·og:image(2026-11-25 운영 QA-08)와 공유 화면의 og:image(링크 미리보기, 2026-11-27). 절대 주소는 robots.txt·sitemap.xml(app/search_robots.py)처럼
# 공개 주소 설정(DATEMATE_PUBLIC_ORIGIN, Worker 의 PUBLIC_ORIGIN)에서만 만들고 Host 머리글은 믿지 않는다.
# index.html 에는 자리표시 PUBLIC_ORIGIN_TOKEN 을 적어 두고 보낼 때 바꾼다. 공개 주소가 없으면(개발) 자리표시가 든 태그를 뺀다.
# Worker 가 컨테이너 대신 첫 화면을 줄 때(cloudflare/edge.mjs withPublicOrigin)도 같은 규칙이다 — 두 쪽 결과를 tests 가 비교한다.
PUBLIC_ORIGIN_TOKEN = "{{PUBLIC_ORIGIN}}"
_ORIGIN_TAG = re.compile(r"<(?:link|meta)\b[^>]*\{\{PUBLIC_ORIGIN\}\}[^>]*>")


def with_public_origin(html, origin):
    if not origin:
        return _ORIGIN_TAG.sub("", html)
    return html.replace(PUBLIC_ORIGIN_TOKEN, escape(origin, quote=True))


